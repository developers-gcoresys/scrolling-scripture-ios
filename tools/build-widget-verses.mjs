#!/usr/bin/env node
// Builds App/Resources/widget_verses.json from the canonical World English
// Bible text. The widget reads this small rotation instead of the full 4.6 MB
// edition, which keeps the WidgetKit extension inside its memory budget.
//
// Usage: node tools/build-widget-verses.mjs [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "App/Resources/world_english_bible.json");
const outputPath = resolve(root, "App/Resources/widget_verses.json");

// A stable rotation of well-known verses. Keep this list reviewed alongside the
// canonical text; the script fails if a reference no longer exists.
const REFERENCES = [
  "Genesis 1:1", "Genesis 28:15", "Exodus 14:14", "Deuteronomy 31:6",
  "Joshua 1:9", "1 Chronicles 16:11", "Nehemiah 8:10", "Job 19:25",
  "Psalm 16:8", "Psalm 23:1", "Psalm 27:1", "Psalm 34:8", "Psalm 37:4",
  "Psalm 46:10", "Psalm 91:1", "Psalm 119:105", "Psalm 121:1", "Psalm 139:14",
  "Proverbs 3:5", "Proverbs 16:3", "Proverbs 18:10", "Ecclesiastes 3:1",
  "Isaiah 26:3", "Isaiah 40:31", "Isaiah 41:10", "Jeremiah 29:11",
  "Lamentations 3:22", "Micah 6:8", "Habakkuk 3:19", "Zephaniah 3:17",
  "Matthew 4:4", "Matthew 5:14", "Matthew 5:16", "Matthew 6:33",
  "Matthew 7:7", "Matthew 11:28", "Matthew 28:19", "Mark 12:30",
  "Luke 1:37", "Luke 6:31", "John 1:1", "John 3:16", "John 8:12",
  "John 10:10", "John 11:25", "John 14:6", "John 14:27", "John 15:5",
  "Acts 1:8", "Romans 5:8", "Romans 8:28", "Romans 8:38", "Romans 10:9",
  "Romans 12:2", "1 Corinthians 10:13", "1 Corinthians 13:4",
  "1 Corinthians 13:13", "2 Corinthians 5:17", "2 Corinthians 12:9",
  "Galatians 2:20", "Galatians 5:22", "Ephesians 2:8", "Ephesians 4:32",
  "Ephesians 6:10", "Philippians 4:6", "Philippians 4:8", "Philippians 4:13",
  "Colossians 3:2", "Colossians 3:23", "1 Thessalonians 5:11",
  "1 Thessalonians 5:16", "2 Timothy 1:7", "Hebrews 11:1", "Hebrews 12:2",
  "Hebrews 13:8", "James 1:5", "James 1:22", "1 Peter 5:7", "1 John 1:9",
  "1 John 3:1", "1 John 4:19", "Revelation 21:4"
];

const bible = JSON.parse(readFileSync(sourcePath, "utf8"));
// Common display names that differ from the edition's book names.
const BOOK_ALIASES = { Psalm: "Psalms" };
const verses = REFERENCES.map((reference) => {
  const match = reference.match(/^(.*) (\d+):(\d+)$/);
  if (!match) throw new Error(`Unparseable reference: ${reference}`);
  const [, rawBookName, chapterNumber, verseNumber] = match;
  const bookName = BOOK_ALIASES[rawBookName] ?? rawBookName;
  const book = bible.books.find((candidate) => candidate.name === bookName);
  if (!book) throw new Error(`Unknown book in reference: ${reference}`);
  const chapter = book.chapters.find((candidate) => candidate.number === Number(chapterNumber));
  if (!chapter) throw new Error(`Unknown chapter in reference: ${reference}`);
  const verse = chapter.verses.find((candidate) => String(candidate.number) === verseNumber);
  if (!verse) throw new Error(`Unknown verse in reference: ${reference}`);
  return { reference, text: String(verse.text).trim() };
});

const payload = {
  translation: bible.translation,
  abbreviation: bible.abbreviation,
  source: bible.source,
  sourceUpdated: bible.sourceUpdated,
  note: "Generated by tools/build-widget-verses.mjs. Do not edit by hand.",
  verses
};
const output = `${JSON.stringify(payload, null, 2)}\n`;

if (process.argv.includes("--check")) {
  const existing = readFileSync(outputPath, "utf8");
  if (existing !== output) {
    console.error("DRIFT: App/Resources/widget_verses.json is stale. Run tools/build-widget-verses.mjs.");
    process.exit(1);
  }
  console.log(`widget_verses.json is current (${verses.length} verses)`);
} else {
  writeFileSync(outputPath, output);
  console.log(`Wrote ${verses.length} widget verses to App/Resources/widget_verses.json`);
}
